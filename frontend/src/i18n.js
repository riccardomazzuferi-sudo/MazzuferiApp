const I18nContext = createContext({ lang: "it", t: (k) => k, setLang: () => {} });

export const I18nProvider = ({ children }) => {
  const [lang, setLangState] = useState(() => localStorage.getItem("mold_lang") || "it");
  useEffect(() => { localStorage.setItem("mold_lang", lang); }, [lang]);
  const t = (k) => translations[lang][k] ?? translations.it[k] ?? k;
  const setLang = (l) => setLangState(l);
  return <I18nContext.Provider value={{ lang, t, setLang }}>{children}</I18nContext.Provider>;
};

export const useI18n = () => useContext(I18nContext);
